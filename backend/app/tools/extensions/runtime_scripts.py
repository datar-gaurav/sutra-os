"""Runtime Scripts extension for Sutra OS — bridge-client edition.

All task validation and file I/O live in the host-side dispatcher_bridge.py daemon.
This extension is a thin HTTP client that talks to the bridge over
http://host.docker.internal:PORT using a shared bearer token.

Configure via Settings > Integrations > Extensions:
  bridge_url   (config)      — e.g. http://host.docker.internal:7475
  bridge_token (credential)  — shared bearer token (set by install.sh)

Provides:
  - runtime_scripts_add_task:      queue a task into tasks.md
  - runtime_scripts_trigger_run:   fire-and-forget scripts/run.sh via the bridge
  - runtime_scripts_list_tasks:    show pending / in_progress / done
  - runtime_scripts_get_status:    show active task, plan, needs-human, logs
"""

